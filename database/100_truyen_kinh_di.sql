“Mẹ…” cậu vô thức gọi.

Người phụ nữ mỉm cười. Những vết nứt trên da mặt tách rộng ra như miệng một vết thương.

“Con nhớ mẹ rồi.”

Cậu bé trong tủ hét lên:

“Chạy đi!”

